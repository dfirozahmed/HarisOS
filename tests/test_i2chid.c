static int has_reg(const AmlI2cHid *d, unsigned v)
{
    for (int i = 0; i < d->nregs; i++)
        if (d->regs[i] == v)
            return 1;
    return 0;
}

static void test_touchpad_device(void)
{
    AmlI2cHid d[4];
    int n = aml_find_i2c_hid(TPD0, sizeof TPD0, d, 4);
    assert(n == 1); /* _CID shows up once; the two identical buffers must not give two devices */
    assert(d[0].addr == 0x15);
    assert(d[0].speed == 400000);
    assert(strcmp(d[0].ctrl, "I2CD") == 0);
    assert(d[0].has_gpio && d[0].gpio_pin == 9 && d[0].gpio_active_low);
    assert(strcmp(d[0].gpio_ctrl, "GPIO") == 0);
    assert(has_reg(&d[0], 0x20) && has_reg(&d[0], 1)); /* Return (0x20) / Return (One) of the _DSM */
}

static void test_controllers(void)
{
    AmlDevice c;
    assert(aml_find_device(I2CD, sizeof I2CD, "I2CD", &c));
    assert(strcmp(c.hid, "AMDI0010") == 0);
    assert(c.has_mem && c.base == 0xFEDC5000ULL && c.size == 0x1000);
    assert(!c.has_adr);

    assert(aml_find_device(GPIO, sizeof GPIO, "GPIO", &c));
    assert(strcmp(c.hid, "AMDI0030") == 0);
    assert(c.has_mem && c.base == 0xFED81500ULL && c.size == 0x400); /* the first range: the pin registers */

    assert(!aml_find_device(I2CD, sizeof I2CD, "NOPE", &c));
}

static void test_garbage(void)
{
    unsigned char junk[512];
    for (unsigned i = 0; i < sizeof junk; i++)
        junk[i] = (unsigned char)(i * 7 + 3);
    AmlI2cHid d[2];
    AmlDevice c;
    assert(aml_find_i2c_hid(junk, sizeof junk, d, 2) == 0);
    assert(!aml_find_device(junk, sizeof junk, "I2C0", &c));
    assert(aml_find_i2c_hid(TPD0, 5, d, 2) == 0); /* truncated input must not read past the end */
}

static void test_hid_value(void)
{
    const unsigned char r[] = {0xA5, 0xFF, 0x7F, 0x80};
    assert(hid_value(r, 4, 0, 4, 0) == 5);
    assert(hid_value(r, 4, 4, 4, 0) == 10);
    assert(hid_value(r, 4, 8, 8, 1) == -1);
    assert(hid_value(r, 4, 8, 8, 0) == 255);
    assert(hid_value(r, 4, 16, 16, 1) == (long)(short)0x807F);
    assert(hid_value(r, 4, 28, 8, 0) == 0x08); /* bits past the end read as zero */
    assert(hid_value(r, 4, 0, 0, 0) == 0);
}

static void test_boot_mouse(void)
{
    static const unsigned char D[] = {0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01,
                                      0x29, 0x03, 0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01,
                                      0x75, 0x05, 0x81, 0x03, 0x05, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81,
                                      0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06, 0xC0, 0xC0};
    HidMouse m;
    assert(hid_find_mouse(D, sizeof D, &m));
    assert(!m.uses_ids);
    assert(m.btn_off == 0 && m.btn_n == 3);
    assert(m.x_off == 8 && m.x_size == 8 && m.x_signed);
    assert(m.y_off == 16 && m.y_size == 8 && m.y_signed);
    assert(m.has_wheel && m.w_off == 24 && m.w_size == 8 && m.w_signed);

    const unsigned char rep[] = {0x05, 0xFE, 0x03, 0xFF}; /* left + middle, x = -2, y = 3, wheel = -1 */
    assert(hid_value(rep, 4, m.btn_off, m.btn_n, 0) == 5);
    assert(hid_value(rep, 4, m.x_off, m.x_size, m.x_signed) == -2);
    assert(hid_value(rep, 4, m.y_off, m.y_size, m.y_signed) == 3);
    assert(hid_value(rep, 4, m.w_off, m.w_size, m.w_signed) == -1);
}

/* A precision touchpad's mouse collection: it has a report ID, comes after another collection with
 * its own ID, and has 16-bit axes and no wheel. */
static void test_touchpad_mouse_collection(void)
{
    static const unsigned char D[] = {
        0x06, 0x00, 0xFF, 0x09, 0x01, 0xA1, 0x01, 0x85, 0x01, 0x09, 0x02, 0x15, 0x00, 0x26, 0xFF, 0x00, 0x75, 0x08, 0x95,
        0x04, 0x81, 0x02, 0xC0, /* vendor collection, ID 1, 4 bytes */
        0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x04, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x02,
        0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x02, 0x81, 0x02, 0x95, 0x06, 0x81, 0x03, 0x05, 0x01, 0x09, 0x30,
        0x09, 0x31, 0x16, 0x00, 0x80, 0x26, 0xFF, 0x7F, 0x75, 0x10, 0x95, 0x02, 0x81, 0x06, 0xC0, 0xC0};
    HidMouse m;
    assert(hid_find_mouse(D, sizeof D, &m));
    assert(m.uses_ids && m.report_id == 4);
    assert(m.btn_off == 0 && m.btn_n == 2);
    assert(m.x_off == 8 && m.x_size == 16 && m.x_signed);
    assert(m.y_off == 24 && m.y_size == 16 && m.y_signed);
    assert(!m.has_wheel);
}

/* Absolute X / Y (a touchscreen or a plain digitizer) is not a mouse. */
static void test_absolute_is_not_a_mouse(void)
{
    static const unsigned char D[] = {0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x01, 0x09, 0x30,
                                      0x09, 0x31, 0x15, 0x00, 0x26, 0xFF, 0x0F, 0x75, 0x10, 0x95, 0x02, 0x81, 0x02, 0xC0,
                                      0xC0};
    HidMouse m;
    assert(!hid_find_mouse(D, sizeof D, &m));
    assert(!hid_find_mouse(D, 3, &m));
    assert(!hid_find_mouse(D, 0, &m));
}


/* ---- ACPI table walking: build RSDP -> XSDT -> FADT (-> DSDT) + SSDT by hand ---- */
static void put32(unsigned char *p, unsigned v)
{
    for (int i = 0; i < 4; i++)
        p[i] = (unsigned char)(v >> (8 * i));
}

static void put64(unsigned char *p, unsigned long long v)
{
    put32(p, (unsigned)v);
    put32(p + 4, (unsigned)(v >> 32));
}

static void seal(unsigned char *t, const char *sig, unsigned len, unsigned sum_at)
{
    memcpy(t, sig, 4);
    put32(t + 4, len);
    t[sum_at] = 0;
    unsigned char s = 0;
    for (unsigned i = 0; i < len; i++)
        s = (unsigned char)(s + t[i]);
    t[sum_at] = (unsigned char)(0 - s);
}

static void test_acpi_walk(void)
{
    static unsigned char dsdt[36 + sizeof TPD0], ssdt[40], fadt[276], xsdt[36 + 16], rsdp[36];
    memset(dsdt, 0, sizeof dsdt);
    memset(ssdt, 0, sizeof ssdt);
    memset(fadt, 0, sizeof fadt);
    memset(xsdt, 0, sizeof xsdt);
    memset(rsdp, 0, sizeof rsdp);

    memcpy(dsdt + 36, TPD0, sizeof TPD0);
    seal(dsdt, "DSDT", sizeof dsdt, 9);
    seal(ssdt, "SSDT", sizeof ssdt, 9);
    put64(fadt + 140, (unsigned long long)(size_t)dsdt); /* X_DSDT */
    seal(fadt, "FACP", sizeof fadt, 9);
    put64(xsdt + 36, (unsigned long long)(size_t)fadt);
    put64(xsdt + 44, (unsigned long long)(size_t)ssdt);
    seal(xsdt, "XSDT", sizeof xsdt, 9);
    memcpy(rsdp, "RSD PTR ", 8);
    rsdp[15] = 2;
    put32(rsdp + 20, 36);
    put64(rsdp + 24, (unsigned long long)(size_t)xsdt);
    unsigned char s = 0;
    for (int i = 0; i < 20; i++)
        s = (unsigned char)(s + rsdp[i]);
    rsdp[8] = (unsigned char)(0 - s);

    acpi_init((unsigned long long)(size_t)rsdp);
    assert(acpi_aml_count() == 2);
    unsigned len = 0;
    const unsigned char *t = acpi_aml(0, &len); /* the DSDT comes first (it is found through the FADT) */
    assert(t == dsdt && len == sizeof dsdt);
    t = acpi_aml(1, &len);
    assert(t == ssdt && len == sizeof ssdt);
    assert(acpi_aml(2, &len) == 0);

    ssdt[20] ^= 1; /* a table whose checksum is wrong is ignored */
    acpi_init((unsigned long long)(size_t)rsdp);
    assert(acpi_aml_count() == 1);

    rsdp[8] ^= 1; /* a bad RSDP gives nothing */
    acpi_init((unsigned long long)(size_t)rsdp);
    assert(acpi_aml_count() == 0);
    acpi_init(0);
    assert(acpi_aml_count() == 0);
}

